"""The docs describe the studio as it is now (AGENTS.md, «Документация в том же PR»; .claude/skills/docs-tidy).

Only what is history in every context is caught here: «как раньше», «по-прежнему», «теперь», a PR or issue number,
a file name that is not in the repository, a doc over its size. What needs judgment (a fact that went stale, a
paragraph where a line does) is the docs-tidy skill's work.
"""

import re
import shutil
import subprocess
from pathlib import Path

import pytest

pytestmark = pytest.mark.no_db

ROOT = Path(__file__).resolve().parent.parent
# decisions keep their history by design; reference is generated by make docs; vendor is not ours
SKIP = re.compile(r"^(docs/(decisions|reference|research)/|app/static/vendor/)")

# the skill lists these phrasings as what to look for
HISTORY_SKIP = {".claude/skills/docs-tidy/SKILL.md"}
HISTORY = re.compile(
    r"\bкак (?:и )?раньше\b|\bпо-прежнему\b|\bтеперь\b|\bДополнено\b"
    r"|\((?:PR |issue )?#\d+\)|\b(?:PR|issue|Issue) #\d+"
    r"|\bno longer\b|\bused to\b|\bpreviously\b|\bas before\b|\banymore\b",
    re.IGNORECASE,
)
FILE_NAME = re.compile(r"`([\w./-]+\.(?:py|js|mjs|md|sql|sh|json|css|html|ya?ml|toml))`")
# a pattern (NN-имя.mjs), a URL path, a path relative to its own file
NOT_A_FILE = re.compile(r"NN|имя|^/|^\.\./")

# words, a ceiling for each big doc: a doc grows past it only by a decision, lowered when a tidy shrinks the doc
BUDGET = {
    "README.md": 10500,
    ".claude/skills/telegram-rich-posts/SKILL.md": 5200,
    "docs/ARCHITECTURE.md": 4100,
    "docs/OBSERVABILITY.md": 2500,
}


def _tracked() -> list[str]:
    git = shutil.which("git")
    if not git:
        pytest.skip("нужен git: документы — это файлы репозитория")
    # new files too, before they are added; what .gitignore leaves out is not the repository's
    files = [git, "ls-files", "--cached", "--others", "--exclude-standard"]
    return subprocess.run(files, cwd=ROOT, capture_output=True, text=True, check=True).stdout.split()  # noqa: S603 - fixed args


def _docs(tracked: list[str]) -> list[str]:
    return [f for f in tracked if f.endswith(".md") and not SKIP.match(f) and (ROOT / f).exists()]


def test_the_docs_tell_the_current_state_not_its_history():
    found = []
    for f in _docs(_tracked()):
        if f in HISTORY_SKIP:
            continue
        for n, line in enumerate((ROOT / f).read_text(encoding="utf-8").splitlines(), 1):
            found += [f"{f}:{n}: «{m.group(0)}»" for m in HISTORY.finditer(line)]
    assert not found, (
        "документация описывает студию как она есть: что изменилось и почему — в коммите и описании PR, решение на "
        "будущее — в docs/decisions/, ссылка на источник — путь к файлу, а не номер PR (.claude/skills/docs-tidy):\n"
        + "\n".join(found)
    )


def test_every_file_a_doc_names_is_in_the_repository():
    tracked = _tracked()
    names = set(tracked)
    missing = []
    for f in _docs(tracked):
        for n, line in enumerate((ROOT / f).read_text(encoding="utf-8").splitlines(), 1):
            for m in FILE_NAME.finditer(line):
                name = m.group(1).removeprefix("./")
                if NOT_A_FILE.search(name) or name in names or any(t.endswith("/" + name) for t in tracked):
                    continue
                missing.append(f"{f}:{n}: {m.group(1)}")
    assert not missing, "документ называет файл, которого нет в репозитории:\n" + "\n".join(missing)


@pytest.mark.parametrize("doc", sorted(BUDGET))
def test_a_big_doc_stays_within_its_budget(doc):
    words = len((ROOT / doc).read_text(encoding="utf-8").split())
    assert words <= BUDGET[doc], (
        f"{doc}: {words} слов при бюджете {BUDGET[doc]}. Сначала сократите по .claude/skills/docs-tidy; "
        "поднимать бюджет — решение, а не способ пройти тест"
    )
