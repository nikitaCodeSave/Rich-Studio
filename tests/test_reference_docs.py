"""docs/reference/ is generated from the code: the HTTP routes (OpenAPI) and the MCP tools.

README and SKILL.md link to these files instead of keeping their own lists, so a PR that adds a route or a tool
touches no shared hand-written table. The text comes from the route's summary and docstring and from the tool's
docstring. After an intended change run `make docs` (or `make openapi`) and commit the result.
"""

import asyncio
import os
from pathlib import Path

import pytest

REF = Path(__file__).resolve().parent.parent / "docs" / "reference"
HEADER = "<!-- generated by tests/test_reference_docs.py: run `make docs`, do not edit by hand -->"
TAGS = {
    "posts": "Проверка поста",
    "preview": "Предпросмотр",
    "drafts": "Черновики",
    "telegram": "Публикация и канал",
    "channels": "Каналы",
    "media": "Файлы",
    "spec": "Спецификация Bot API",
    "service": "Студия",
}
KINDS = [  # (readOnly, destructive, openWorld) → what the tool does
    ("публикует или меняет канал", lambda a: a.get("destructiveHint") is True),
    ("ходит в Telegram или в сеть", lambda a: a.get("openWorldHint") is True and not a.get("readOnlyHint")),
    ("читает Telegram", lambda a: a.get("openWorldHint") is True),
    ("меняет данные студии", lambda a: not a.get("readOnlyHint")),
    ("только читает", lambda a: True),
]


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def http_api() -> str:
    import main

    schema = main.app.openapi()
    rows: dict[str, list[str]] = {}
    for path, ops in schema["paths"].items():
        for method, op in ops.items():
            text = op.get("summary", "")
            if op.get("description"):
                text += ". " + op["description"]
            tag = (op.get("tags") or ["other"])[0]
            rows.setdefault(tag, []).append(f"| `{method.upper()} {path}` | {_cell(text)} |")
    out = [HEADER, "", "# HTTP API", "", "Все маршруты студии. Интерактивно с примерами: `/docs` работающей студии."]
    for tag in sorted(rows, key=lambda t: list(TAGS).index(t) if t in TAGS else len(TAGS)):
        out += ["", f"## {TAGS.get(tag, tag)}", "", "| Маршрут | Что делает |", "|---|---|", *sorted(rows[tag])]
    return "\n".join(out) + "\n"


def mcp_tools() -> str:
    import mcp_tools
    import settings

    cfg = settings.get()
    publish, cfg.mcp_publish = cfg.mcp_publish, True  # the full list, whatever MCP_PUBLISH the shell has
    try:
        tools = asyncio.run(mcp_tools.build().list_tools())
    finally:
        cfg.mcp_publish = publish
    out = [
        HEADER,
        "",
        f"# Инструменты MCP ({len(tools)})",
        "",
        "Сервер `/mcp`. Инструментов вида «публикует или меняет канал» нет при `MCP_PUBLISH=off`.",
        "",
        "| Инструмент | Что делает | Вид |",
        "|---|---|---|",
    ]
    for t in sorted(tools, key=lambda t: t.name):
        ann = t.annotations.model_dump(by_alias=True, exclude_none=True) if t.annotations else {}
        kind = next(k for k, test in KINDS if test(ann))
        out.append(f"| `{t.name}` | {_cell(t.description or '')} | {kind} |")
    return "\n".join(out) + "\n"


@pytest.mark.parametrize("name, build", [("http-api.md", http_api), ("mcp-tools.md", mcp_tools)])
def test_reference_is_current(name, build):
    path = REF / name
    if os.environ.get("UPDATE_DOCS"):  # `make docs`
        REF.mkdir(exist_ok=True)
        path.write_text(build(), "utf-8")
    assert path.exists(), f"docs/reference/{name} is missing: run `make docs`"
    assert build() == path.read_text("utf-8"), f"docs/reference/{name} is stale: run `make docs` and commit it"


def test_every_route_says_what_it_does():
    """A route without summary= gets FastAPI's English title of the function name: that is not documentation."""
    import main

    for path, ops in main.app.openapi()["paths"].items():
        for method, op in ops.items():
            assert any("а" <= ch <= "я" for ch in op.get("summary", "").lower()), f"{method.upper()} {path}: summary="


def documented_tools() -> set[str]:
    text = (REF / "mcp-tools.md").read_text("utf-8")
    return {line.split("`")[1] for line in text.splitlines() if line.startswith("| `")}
